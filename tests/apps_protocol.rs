//! Protocol fixtures captured from Python, including protocol-5 pickle decoding.
use runpod::{
    Value,
    apps::{
        protocol::FunctionRequest,
        serialization,
        targets::{
            JobOptions, args_to_input, merge_job_options, unwrap_job_output, unwrap_live_output,
        },
    },
    json,
};

#[test]
fn python_invocation_helpers_and_pickle_values() {
    let cases: Vec<Value> = serde_json::from_str(include_str!("fixtures/invocation.json")).unwrap();
    let mut encoded = Vec::new();
    for case in cases {
        let input = &case["input"];
        let result = match case["operation"].as_str().unwrap() {
            "args_to_input" => args_to_input(
                "fn",
                &["a".into(), "b".into(), "c".into()],
                input["args"].as_array().unwrap(),
                input["kwargs"].as_object().unwrap(),
            )
            .map(Value::Object),
            "unwrap_job_output" => unwrap_job_output(input),
            "live_unwrap" => unwrap_live_output(input),
            "build_job_options" => Ok(serde_json::from_value::<JobOptions>(input.clone())
                .unwrap()
                .to_payload()),
            "merge_job_options" => merge_job_options(&input["base"], &input["new"]),
            "function_request" => serde_json::from_value::<FunctionRequest>(input.clone())
                .unwrap()
                .to_input(),
            "pickle" => {
                let data = serialization::serialize_arg(input).unwrap();
                encoded.push(json!({"encoded":data,"expected":input}));
                serialization::deserialize_result::<Value>(case["encoded"].as_str().unwrap())
            }
            other => panic!("unmapped fixture {other}"),
        };
        if let Some(error) = case.get("error") {
            assert_eq!(
                result.unwrap_err().to_string(),
                error.as_str().unwrap(),
                "{case}"
            );
        } else {
            assert_eq!(result.unwrap(), case["output"], "{case}");
        }
    }
    // A separate Python verification step loads bytes actually generated by Rust.
    std::fs::create_dir_all("test-results").unwrap();
    std::fs::write(
        "test-results/rust-pickle.json",
        serde_json::to_vec(&encoded).unwrap(),
    )
    .unwrap();
}

#[test]
fn malformed_serialization_returns_errors() {
    assert!(serialization::deserialize_result::<Value>("!invalid").is_err());
    assert!(serialization::deserialize_result::<Value>("bm90IGEgcGlja2xl").is_err());
}
